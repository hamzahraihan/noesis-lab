/** Glyph pixel width, excluding the inter-character gap. */
export const GLYPH_WIDTH = 5;

/** Rows a glyph occupies. */
export const GLYPH_HEIGHT = 7;

/** Pixels between characters. */
export const GLYPH_SPACING = 1;

/** Advance in pixels for one character cell. */
export const GLYPH_ADVANCE = GLYPH_WIDTH + GLYPH_SPACING;

/**
 * Column bytes for a character, folded to uppercase.
 *
 * Anything outside the font's range renders as a space rather than garbage,
 * which keeps a stray character from filling a panel with noise.
 */
export function glyphFor(character: string): Glyph {
  const folded = character.toUpperCase();
  return GLYPHS[folded] ?? SPACE;
}

/** Pixel width a string will occupy, including its trailing inter-character gap. */
export function measureText(text: string): number {
  return text.length === 0 ? 0 : text.length * GLYPH_ADVANCE - GLYPH_SPACING;
}