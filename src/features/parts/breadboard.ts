/**
 * Full-size solderless breadboard, 63 columns by 10 tie-point rows.
 *
 * Geometry is in real millimetres at 1:1, because the whole point of the
 * simulator is that hole pitch matches a real board -- you should be able to
 * measure a screenshot against a breadboard on your desk.
 *
 * Two details carry most of the teaching value and are modelled exactly:
 *   - each column is two independent 5-hole strips (a-e and f-j), and
 *   - each power rail is split down the middle, so the two halves are not
 *     connected and bridging them is a real wiring mistake you can make.
 */

import type { PartDefinition, PinSpec } from './catalog';

export const COLUMN_COUNT = 63;
export const COLUMN_PITCH_MM = 2.54;
export const ROW_PITCH_MM = 2.54;

/** Columns 0..30 form the left half of every rail; 31..62 the right. */
export const RAIL_SPLIT_COLUMN = 31;

/** Row letters as printed on a real board, top strip then bottom strip. */
export const ROW_LETTERS = ['a', 'b', 'c', 'd', 'e', 'f', 'g', 'h', 'i', 'j'] as const;

/** Rail rows: 0 top positive, 1 top negative, 2 bottom negative, 3 bottom positive. */
export const RAIL_COUNT = 4;
/** Rail polarity, as silkscreened on the board. */
export const RAIL_POLARITY = ['+', '-', '-', '+'] as const;

const LEFT_MARGIN_MM = 5.08;
const TOP_RAIL_POSITIVE_Y_MM = 6.35;
const RAIL_ROW_PITCH_MM = 2.54;
const FIRST_STRIP_Y_MM = 15.24;
/** Gap between row e and row f: the channel that lets pins straddle the board. */
const CENTRE_CHANNEL_MM = 7.62;
const BOTTOM_RAIL_NEGATIVE_Y_MM = 45.72;

export const BREADBOARD_WIDTH_MM = LEFT_MARGIN_MM * 2 + (COLUMN_COUNT - 1) * COLUMN_PITCH_MM;
export const BREADBOARD_HEIGHT_MM = BOTTOM_RAIL_NEGATIVE_Y_MM + 3 * RAIL_ROW_PITCH_MM + 5.08;

/** Centre x of a column, measured from the board's left edge. */
export function columnX(column: number): number {
  return LEFT_MARGIN_MM + column * COLUMN_PITCH_MM;
}

/** Centre y of a strip row (0 = row a) measured from the board's top edge. */
export function stripRowY(row: number): number {
  if (row < 5) return FIRST_STRIP_Y_MM + row * ROW_PITCH_MM;
  return FIRST_STRIP_Y_MM + 4 * ROW_PITCH_MM + CENTRE_CHANNEL_MM + (row - 5) * ROW_PITCH_MM;
}

/** Centre y of a rail row, indexed as described by `RAIL_COUNT`. */
export function railRowY(rail: number): number {
  if (rail < 2) return TOP_RAIL_POSITIVE_Y_MM + rail * RAIL_ROW_PITCH_MM;
  return BOTTOM_RAIL_NEGATIVE_Y_MM + (rail - 2) * RAIL_ROW_PITCH_MM;
}

/** Net name shared by every hole in one column's top (or bottom) strip. */
export function stripNet(column: number, bottom: boolean): string {
  return `strip:${column}:${bottom ? 'bottom' : 'top'}`;
}

/**
 * Net name for a rail hole. The half component is what makes the centre split
 * real: same rail row, different half, different net.
 */
export function railNet(rail: number, column: number): string {
  return `rail:${rail}:${column < RAIL_SPLIT_COLUMN ? 'left' : 'right'}`;
}

export type HoleRef =
  | { readonly kind: 'strip'; readonly column: number; readonly row: number }
  | { readonly kind: 'rail'; readonly column: number; readonly rail: number };

/** Pin id for a hole, matching the ids generated by the definition below. */
export function holePinId(hole: HoleRef): string {
  return hole.kind === 'strip'
    ? `s${hole.column}${ROW_LETTERS[hole.row]}`
    : `r${hole.rail}_${hole.column}`;
}

/**
 * Resolves a board-local point to the hole it lands on, or null if it misses.
 *
 * The column is checked first, then the two strip blocks and the four rails are
 * tested in turn, nearest match winning. Rail rows deliberately get their own
 * loop: the gap between the top and bottom rail pairs is set by the strip block
 * between them, so they are not one uniform pitch apart and cannot be derived
 * from a single index.
 */
export function holeAt(x: number, y: number): HoleRef | null {
  const column = Math.round((x - LEFT_MARGIN_MM) / COLUMN_PITCH_MM);
  if (column < 0 || column >= COLUMN_COUNT) return null;
  if (Math.abs(x - columnX(column)) > COLUMN_PITCH_MM / 2) return null;

  for (let rail = 0; rail < RAIL_COUNT; rail++) {
    if (Math.abs(y - railRowY(rail)) <= RAIL_ROW_PITCH_MM / 2) {
      return { kind: 'rail', column, rail };
    }
  }

  // Nearest row in the top block (a-e) and the bottom block (f-j).
  const topCandidate = Math.round((y - FIRST_STRIP_Y_MM) / ROW_PITCH_MM);
  const bottomStartY = FIRST_STRIP_Y_MM + 4 * ROW_PITCH_MM + CENTRE_CHANNEL_MM;
  const bottomCandidate = Math.round((y - bottomStartY) / ROW_PITCH_MM);

  const topDistance = Math.abs(y - stripRowY(topCandidate));
  const bottomDistance = Math.abs(y - stripRowY(5 + bottomCandidate));
  const row = topDistance <= bottomDistance ? topCandidate : 5 + bottomCandidate;
  if (row >= 0 && row < 10 && Math.abs(y - stripRowY(row)) <= ROW_PITCH_MM / 2) {
    return { kind: 'strip', column, row };
  }

  return null;
}

function stripPins(): PinSpec[] {
  const pins: PinSpec[] = [];
  for (let column = 0; column < COLUMN_COUNT; column++) {
    for (let row = 0; row < 10; row++) {
      pins.push({
        id: holePinId({ kind: 'strip', column, row }),
        label: '',
        x: columnX(column),
        y: stripRowY(row),
        net: stripNet(column, row >= 5),
      });
    }
  }
  return pins;
}

function railPins(): PinSpec[] {
  const pins: PinSpec[] = [];
  for (let rail = 0; rail < RAIL_COUNT; rail++) {
    for (let column = 0; column < COLUMN_COUNT; column++) {
      pins.push({
        id: holePinId({ kind: 'rail', column, rail }),
        label: '',
        x: columnX(column),
        y: railRowY(rail),
        net: railNet(rail, column),
      });
    }
  }
  return pins;
}

let cached: PartDefinition | null = null;

/**
 * The breadboard definition, built once and shared.
 *
 * 882 pin specs is a lot of objects, but they are immutable and shared by every
 * breadboard on the bench, so the cost is paid once at startup.
 */
export function breadboardDefinition(): PartDefinition {
  if (cached) return cached;
  cached = {
    id: 'breadboard-830',
    name: 'Solderless Breadboard',
    category: 'breadboard',
    widthMm: BREADBOARD_WIDTH_MM,
    heightMm: BREADBOARD_HEIGHT_MM,
    component: { kind: 'breadboard' },
    pins: [...stripPins(), ...railPins()],
    bodyColour: '#e8e6e1',
    legendColour: '#5a5a5a',
  };
  return cached;
}
